"""Bounded, frame-addressed RGB access to local LeRobot image datasets."""

from __future__ import annotations

from collections import OrderedDict
import hashlib
from pathlib import Path

import torch

__all__ = ["LeRobotImageReader"]


class LeRobotImageReader:
    """Read individual PNG frames without materializing an image corpus.

    Frame identities use the SDK's ``episode_index`` and ``frame_index``,
    matching the default identity generated by :class:`LeRobotDataSource`.
    Only image features are supported; video timestamp decoding is separate.
    The bounded cache contains uint8 CHW frames and returns owned tensors.

    Args:
        root: Local LeRobot dataset directory.
        image_key: RGB feature name.
        repo_id: Local dataset identity expected by the SDK.
        cache_bytes: Maximum resident decoded-image storage in bytes.
    """

    def __init__(
        self,
        root: str | Path,
        image_key: str,
        *,
        repo_id: str = "local/dataset",
        cache_bytes: int = 512 * 1024**2,
    ) -> None:
        if type(cache_bytes) is not int or cache_bytes < 0:
            raise ValueError("cache_bytes must be a nonnegative integer")
        from lerobot.datasets.lerobot_dataset import LeRobotDataset

        self.root = Path(root).resolve()
        self.dataset = LeRobotDataset(repo_id, root=self.root, download_videos=False)
        feature = self.dataset.features.get(image_key, {})
        if feature.get("dtype") != "image":
            raise ValueError(f"{image_key} must name a LeRobot image feature")
        shape = tuple(feature.get("shape", ()))
        if len(shape) != 3 or shape[-1] != 3:
            raise ValueError("Image feature must declare HWC RGB shape")
        self.image_key, self.shape, self.cache_bytes = image_key, shape, cache_bytes
        self._cache: OrderedDict[tuple[int, int], torch.Tensor] = OrderedDict()
        self._bytes = 0
        backing = self.dataset.hf_dataset
        if backing is None or not hasattr(backing, "select_columns"):
            raise ValueError("LeRobot image reader requires backing-column access")
        # Restrict decoding to this camera even when the dataset has other
        # image or video features. Numeric sampling is owned separately.
        self._images = backing.select_columns([image_key])
        columns = backing.select_columns(["episode_index", "frame_index"])
        self._rows: dict[tuple[int, int], int] = {}
        for start in range(0, len(self.dataset), 4096):
            data = columns[start : start + 4096]
            for offset, (episode, frame) in enumerate(
                zip(data["episode_index"], data["frame_index"])
            ):
                key = (int(episode), int(frame))
                if min(key) < 0 or key in self._rows:
                    raise ValueError(
                        "Image dataset contains invalid or duplicate frame identities"
                    )
                self._rows[key] = start + offset
        if not self._rows:
            raise ValueError("Image dataset contains no frames")
        self.content_id = self.fingerprint()

    def fingerprint(self) -> str:
        """Hash persisted data and metadata in bounded blocks.

        Returns:
            SHA-256 identity of LeRobot data, metadata and PNG storage.
        """
        files = sorted(
            path
            for directory in ("data", "images", "meta")
            for path in (self.root / directory).rglob("*")
            if path.is_file() and path.suffix in {".parquet", ".json", ".jsonl", ".png"}
        )
        if not files:
            raise ValueError("No persisted LeRobot dataset files found")
        digest = hashlib.sha256()
        digest.update(self.image_key.encode())
        for path in files:
            digest.update(path.relative_to(self.root).as_posix().encode())
            with path.open("rb") as stream:
                for block in iter(lambda: stream.read(1024 * 1024), b""):
                    digest.update(block)
        return digest.hexdigest()

    def validate_frame_order(self, frame_ids: torch.Tensor) -> None:
        """Require numeric frames to follow this dataset's SDK episode order.

        Args:
            frame_ids: Valid canonical IDs flattened in episode/time order.

        Raises:
            ValueError: A numeric frame identity refers to another ordering.
        """
        if (
            frame_ids.device.type != "cpu"
            or frame_ids.dtype != torch.int64
            or frame_ids.ndim != 2
            or frame_ids.shape[1] != 3
        ):
            raise ValueError("Image frame IDs must be CPU int64 [frames, 3]")
        numeric_keys = [(episode, frame) for _, episode, frame in frame_ids.tolist()]
        if numeric_keys != list(self._rows):
            raise ValueError("Numeric and image episode/frame order differs")

    def read(self, frame_ids: torch.Tensor) -> torch.Tensor:
        """Return owned RGB frames for canonical ``[source, episode, frame]`` IDs.

        Args:
            frame_ids: CPU integer tensor ``[B, 3]`` from a numeric source.

        Returns:
            CPU uint8 images ``[B, 3, H, W]``.

        Raises:
            ValueError: IDs or decoded images are invalid.
            KeyError: A requested episode/frame does not exist.
        """
        if (
            frame_ids.device.type != "cpu"
            or frame_ids.dtype != torch.int64
            or frame_ids.ndim != 2
            or frame_ids.shape[1] != 3
        ):
            raise ValueError("Image frame IDs must be CPU int64 [batch, 3]")
        images = []
        for _, episode, frame in frame_ids.tolist():
            key = (episode, frame)
            if key not in self._rows:
                raise KeyError(f"Image frame {key} not found")
            image = self._cache.get(key)
            if image is not None:
                self._cache.move_to_end(key)
            else:
                image = self._images[self._rows[key]][self.image_key]
                if not isinstance(image, torch.Tensor) or tuple(image.shape) != (
                    3,
                    *self.shape[:2],
                ):
                    raise ValueError(f"Invalid decoded image at {key}")
                if not bool(torch.isfinite(image).all()) or bool(
                    ((image < 0) | (image > 1)).any()
                ):
                    raise ValueError(f"Decoded image outside [0,1] at {key}")
                image = image.mul(255).round().to(torch.uint8).contiguous()
                size = image.numel()
                if size <= self.cache_bytes:
                    while self._bytes + size > self.cache_bytes:
                        _, evicted = self._cache.popitem(last=False)
                        self._bytes -= evicted.numel()
                    self._cache[key] = image
                    self._bytes += size
            images.append(image)
        return torch.stack(images)

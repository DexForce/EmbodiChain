"""Animate multiple render-only robot references from one URDF asset.

Use --asset PATH --layers 4 --mode asset --opacity 0.4. Add --viser for
browser visualization, or --headless --output-dir PATH to save native frames.
The sinusoidal reference is generated by this example; RobotVisual only
performs FK and visual placement. Physics does not advance.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from embodichain.cli.sim import add_sim_args_to_parser


def build_parser() -> argparse.ArgumentParser:
    """Create the demo CLI without initializing the simulator."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--asset", type=Path, required=True, help="Robot URDF path.")
    parser.add_argument(
        "--layers", type=int, default=1, help="References per environment."
    )
    parser.add_argument("--mode", choices=("asset", "override"), default="override")
    parser.add_argument("--opacity", type=float, default=0.4)
    parser.add_argument("--root-height", type=float, default=0.85)
    parser.add_argument("--steps", type=int, default=300)
    parser.add_argument(
        "--warmup",
        type=int,
        default=5,
        help="Initial frames excluded from timing statistics.",
    )
    parser.add_argument("--fps", type=float, default=30.0)
    parser.add_argument("--output-dir", type=Path)
    parser.add_argument("--resolution", type=int, nargs=2, default=(640, 480))
    add_sim_args_to_parser(parser)
    return parser


if __name__ == "__main__":
    _cli_args = build_parser().parse_args()

import json
import time
import numpy as np

from embodichain.lab.sim import SimulationManager, SimulationManagerCfg
from embodichain.lab.sim.cfg import DenoisingCfg, RenderCfg, physics_cfg_for_backend
from embodichain.lab.visualization import visualization_cfg_from_args
from embodichain.lab.visualization.markers import (
    RobotVisualAppearanceCfg,
    RobotVisual,
    RobotVisualCfg,
)


def _run(sim: SimulationManager, args: argparse.Namespace) -> dict:
    from dexsim import spawn
    from PIL import Image

    sim.prepare()
    sim.set_ground_plane_visibility(False)
    offsets = sim.arena_offsets.detach().cpu().numpy()
    center = (offsets.min(axis=0) + offsets.max(axis=0)) * 0.5
    center[2] += 0.8
    distance = 2.5 + float(np.linalg.norm(np.ptp(offsets[:, :2], axis=0))) * 1.5
    eye = center + np.array([0.6, -0.8, 0.28]) * distance
    if not args.headless:
        sim.open_window()
        sim.get_world().get_windows().set_look_at(
            eye, center, np.array([0.0, 0.0, 1.0])
        )
    camera = None
    if args.output_dir is not None:
        args.output_dir.mkdir(parents=True, exist_ok=True)
        camera = sim._spawn_scene.builder.result.add_camera(
            spawn.CameraDesc(
                name="reference_preview", resolution=tuple(args.resolution)
            )
        )
        camera.open_camera()
        camera.look_at(eye.tolist(), center.tolist(), [0, 0, 1])
        camera.set_visual_overlay_enabled(True)

    started = time.perf_counter()
    ghost = RobotVisual(
        RobotVisualCfg(
            name="reference",
            asset_path=str(args.asset),
            coordinate_space="env",
            appearance=RobotVisualAppearanceCfg(mode=args.mode, opacity=args.opacity),
        ),
        sim,
    )
    q = np.zeros((sim.num_envs, args.layers, len(ghost.joint_names)), np.float32)
    roots = np.tile(np.eye(4), (sim.num_envs, args.layers, 1, 1))
    roots[..., 2, 3] = args.root_height
    roots[..., 0, 3] = np.arange(args.layers) * 0.12
    ghost.visualize_qpos(q, root_poses=roots)
    sim.get_world()._flush_render_updates()
    create_seconds = time.perf_counter() - started
    update_samples, render_samples = [], []
    next_frame = time.perf_counter()
    for step in range(args.warmup + args.steps):
        phase = step * 0.04 + np.arange(args.layers)[None, :, None] * 0.3
        reference = q + 0.08 * np.sin(phase + np.arange(q.shape[-1]) * 0.4)
        started = time.perf_counter()
        ghost.visualize_qpos(reference, root_poses=roots)
        sim.get_world()._flush_render_updates()
        update_seconds = time.perf_counter() - started
        started = time.perf_counter()
        with sim.render_frame(force_visualization=True, capture_camera_images=False):
            if camera is not None:
                camera.render()
        render_seconds = time.perf_counter() - started
        if step >= args.warmup:
            update_samples.append(update_seconds)
            render_samples.append(render_seconds)
        if camera is not None and step in {args.warmup, args.warmup + args.steps - 1}:
            Image.fromarray(np.array(camera.get_rgb_map(), copy=True)).save(
                args.output_dir / f"{args.mode}-{step:04d}.png"
            )
        if args.fps > 0:
            next_frame += 1 / args.fps
            time.sleep(max(0, next_frame - time.perf_counter()))
    result = dict(
        environments=sim.num_envs,
        layers=args.layers,
        robots=sim.num_envs * args.layers,
        visuals_per_robot=ghost.num_visuals,
        joints=list(ghost.joint_names),
        renderer=args.renderer,
        appearance=args.mode,
        opacity=args.opacity,
        resolution=list(args.resolution),
        render_scope=(
            "synchronous_camera" if camera is not None else "frame_publication"
        ),
        warmup=args.warmup,
        repeats=args.steps,
        create_seconds=create_seconds,
        # Pose publication and camera rendering are timed separately.
        update_seconds=update_samples,
        render_seconds=render_samples,
        median_update_ms=float(np.median(update_samples) * 1000),
        median_render_ms=float(np.median(render_samples) * 1000),
        physics_steps=sim._visualization_sim_step,
    )
    ghost.remove()
    return result


def main(args: argparse.Namespace | None = None) -> None:
    """Run the bounded reference visualization and write optional measurements.

    Args:
        args: Parsed CLI options, or None to read the command line.
    """
    args = build_parser().parse_args() if args is None else args
    if args.layers < 1 or args.steps < 1 or args.num_envs < 1:
        raise ValueError("layers, steps and num_envs must be positive.")
    if args.warmup < 0:
        raise ValueError("warmup must be nonnegative.")
    if not np.isfinite(args.fps) or args.fps < 0:
        raise ValueError("fps must be finite and nonnegative; zero disables pacing.")
    if not np.isfinite(args.root_height):
        raise ValueError("root-height must be finite.")
    if not np.isfinite(args.opacity) or not 0 <= args.opacity <= 1:
        raise ValueError("opacity must be finite and in [0, 1].")
    if min(args.resolution) < 1:
        raise ValueError("resolution dimensions must be positive.")
    if args.output_dir is not None and args.renderer == "no-render":
        raise ValueError("Native frame capture requires a native renderer.")
    sim = SimulationManager(
        SimulationManagerCfg(
            headless=args.headless,
            device=args.device,
            num_envs=args.num_envs,
            arena_space=args.arena_space,
            enable_entity_gizmo=False,
            startup_summary="off",
            width=args.resolution[0],
            height=args.resolution[1],
            render_cfg=RenderCfg(
                renderer=args.renderer,
                denoising=DenoisingCfg(window="off", offscreen="off"),
            ),
            physics_cfg=physics_cfg_for_backend(args.physics),
            visualization=visualization_cfg_from_args(args),
        )
    )
    try:
        result = _run(sim, args)
        if args.output_dir is not None:
            (args.output_dir / "measurements.json").write_text(
                json.dumps(result, indent=2) + "\n"
            )
        print(json.dumps(result, indent=2))
    finally:
        sim.destroy(exit_process=False)
        SimulationManager.flush_cleanup_queue()


if __name__ == "__main__":
    main(_cli_args)
